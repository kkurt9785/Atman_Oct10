-- 2026-11-12 시연 정리 마무리: 운영 197화면 재확인에서 관리자 알림 9건에 옛 시연 이름("광주 광산구 데모워커 02" 등)이 남았다.
-- 11/05에 '데모워커' → '시연 근무자'로 한 번 바뀐 뒤라 오늘 이름 바꾸기(옛 이름 → 사람 이름)에 걸리지 않는 10월 알림이다.
-- 시연 계정이 받은 알림 중 옛 시연 이름이 들어간 것만 지운다(실사용 계정 알림은 건드리지 않는다).
DELETE FROM public.notification_outbox n
WHERE public.is_demo_account(n.worker_auth_user_id)
  AND (n.title ~ '(데모워커|시연 근무자|데모약사|데모간호사|데모직원|긱워커 데모)'
    OR n.body ~ '(데모워커|시연 근무자|데모약사|데모간호사|데모직원|긱워커 데모)');
