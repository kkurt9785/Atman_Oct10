-- ===== Recurring expenses (관리비·학원비): generated by a daily SQL job =====
create table public.hg_recurring_expenses (
  id uuid primary key default gen_random_uuid(),
  family_id uuid not null references public.hg_families(id) on delete cascade,
  title text not null check (length(title) between 1 and 200),
  amount bigint not null check (amount between 1 and 1000000000),
  day_of_month smallint not null check (day_of_month between 1 and 31),
  category text not null default '기타' check (length(category) <= 40),
  payment_method text not null default 'bank_transfer' check (payment_method in ('card','bank_transfer','cash','other')),
  card_id uuid,
  start_month date not null default date_trunc('month', now())::date,
  end_month date,
  active boolean not null default true,
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  foreign key (card_id, family_id) references public.hg_cards(id, family_id),
  check ((payment_method = 'card') = (card_id is not null))
);
alter table public.hg_recurring_expenses enable row level security;
revoke all on public.hg_recurring_expenses from anon, authenticated;
grant select, insert, update, delete on public.hg_recurring_expenses to authenticated;
create policy recurring_family on public.hg_recurring_expenses for all to authenticated using (public.hg_is_member(family_id)) with check (public.hg_is_member(family_id));
create index hg_recurring_family on public.hg_recurring_expenses(family_id);

-- ===== Expense provenance: manual / sms (auto-collected) / recurring; auto rows wait for review =====
alter table public.hg_expenses
  add column source text not null default 'manual' check (source in ('manual','sms','recurring')),
  add column reviewed boolean not null default true,
  add column raw_text text check (length(raw_text) <= 2000),
  add column fingerprint text check (length(fingerprint) <= 80);
create unique index hg_expense_fingerprint on public.hg_expenses(family_id, fingerprint) where fingerprint is not null;
grant update (reviewed) on public.hg_expenses to authenticated;
create index hg_expense_review on public.hg_expenses(family_id, reviewed) where reviewed = false;

create function public.hg_generate_recurring_expenses() returns integer language plpgsql security definer set search_path = '' as $$
declare today date := (now() at time zone 'Asia/Seoul')::date; month date := date_trunc('month', (now() at time zone 'Asia/Seoul'))::date; inserted integer := 0; r record;
begin
  for r in select * from public.hg_recurring_expenses
    where active and start_month <= month and (end_month is null or end_month >= month)
      and least(day_of_month, extract(day from (month + interval '1 month - 1 day'))::int) = extract(day from today)::int
  loop
    insert into public.hg_expenses(family_id, title, amount, date, category, payment_method, card_id, created_by, source, reviewed, fingerprint)
    values (r.family_id, r.title, r.amount, today, r.category, r.payment_method, r.card_id, r.created_by, 'recurring', true, 'rec:' || r.id || ':' || to_char(month, 'YYYY-MM'))
    on conflict do nothing;
    if found then inserted := inserted + 1; end if;
  end loop;
  return inserted;
end $$;
revoke all on function public.hg_generate_recurring_expenses() from public;
do $$ begin
  if not exists (select 1 from cron.job where jobname = 'haraguri-recurring-expenses') then
    perform cron.schedule('haraguri-recurring-expenses', '10 15 * * *', $job$select public.hg_generate_recurring_expenses()$job$); -- 00:10 KST
  end if;
end $$;

-- ===== Auto-collect tokens: one per member per space, used by phone automations (iOS 단축어, MacroDroid) =====
create table public.hg_ingest_tokens (
  token text primary key default encode(extensions.gen_random_bytes(24), 'hex'),
  family_id uuid not null references public.hg_families(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  last_used_at timestamptz,
  received integer not null default 0,
  unique (family_id, user_id)
);
alter table public.hg_ingest_tokens enable row level security;
revoke all on public.hg_ingest_tokens from anon, authenticated;
grant select, insert, delete on public.hg_ingest_tokens to authenticated;
create policy ingest_own on public.hg_ingest_tokens for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid() and public.hg_is_member(family_id));
commit;
begin;
-- Counter bump for the ingest function (service role); kept as a function so the row stays append-friendly.
create function public.hg_bump_ingest(tok text) returns void language sql security definer set search_path = '' as $$
  update public.hg_ingest_tokens set received = received + 1, last_used_at = now() where token = tok;
$$;
revoke all on function public.hg_bump_ingest(text) from public;
commit;
