grant update (display_name) on public.hg_members to authenticated;
create policy member_rename_self on public.hg_members for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
grant update (name) on public.hg_families to authenticated;
create policy family_rename_owner on public.hg_families for update to authenticated using (owner_id = auth.uid()) with check (owner_id = auth.uid());

create function public.hg_leave_family(family uuid) returns void language plpgsql security definer set search_path = '' as $$
declare owner uuid; others int;
begin
  if auth.uid() is null then raise exception '로그인이 필요합니다'; end if;
  select owner_id into owner from public.hg_families where id = family;
  if owner is null then raise exception '모임을 찾을 수 없어요'; end if;
  select count(*) into others from public.hg_members where family_id = family and user_id <> auth.uid();
  if owner = auth.uid() and others > 0 then raise exception '소유자는 다른 멤버가 있는 동안 나갈 수 없어요. 먼저 멤버를 내보내거나 소유권을 넘겨 주세요'; end if;
  if owner = auth.uid() then delete from public.hg_families where id = family; -- last person out closes the space (cascades)
  else delete from public.hg_members where family_id = family and user_id = auth.uid(); end if;
end $$;
create function public.hg_remove_member(family uuid, member uuid) returns void language plpgsql security definer set search_path = '' as $$
begin
  if not exists(select 1 from public.hg_families where id = family and owner_id = auth.uid()) then raise exception '모임 소유자만 멤버를 내보낼 수 있어요'; end if;
  if member = auth.uid() then raise exception '본인은 내보낼 수 없어요. 모임 나가기를 사용하세요'; end if;
  delete from public.hg_members where family_id = family and user_id = member;
end $$;
create function public.hg_transfer_ownership(family uuid, member uuid) returns void language plpgsql security definer set search_path = '' as $$
begin
  if not exists(select 1 from public.hg_families where id = family and owner_id = auth.uid()) then raise exception '모임 소유자만 소유권을 넘길 수 있어요'; end if;
  if not exists(select 1 from public.hg_members where family_id = family and user_id = member) then raise exception '모임 멤버에게만 넘길 수 있어요'; end if;
  update public.hg_families set owner_id = member where id = family;
end $$;
revoke all on function public.hg_leave_family(uuid), public.hg_remove_member(uuid, uuid), public.hg_transfer_ownership(uuid, uuid) from public;
grant execute on function public.hg_leave_family(uuid), public.hg_remove_member(uuid, uuid), public.hg_transfer_ownership(uuid, uuid) to authenticated;
-- A removed member's assignments stay valid rows? No: the FK (family_id, assignee) → hg_members would block the delete, so clear them first.
create function public.hg_clear_assignee() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  update public.hg_entries set assignee = null where family_id = old.family_id and assignee = old.user_id;
  update public.hg_cards set owner_user_id = null where family_id = old.family_id and owner_user_id = old.user_id;
  return old;
end $$;
revoke all on function public.hg_clear_assignee() from public;
create trigger hg_member_leave_cleanup before delete on public.hg_members for each row execute function public.hg_clear_assignee();

